"""Show where a repo keeps its version and what it is now.

    python detect_version.py [repo dir]

Read-only. Prints one line per place found: file:line, version, note. Edit the file with the Edit tool (not sed):
several repos indent the line, and the indent is why a `^version` anchor misses it.
"""
import json
import os
import re
import subprocess
import sys

root = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.getcwd())

PATTERNS = [
    ("gradle.properties", re.compile(r"^\s*((?:mod_)?version|modVersion)\s*=\s*(\S+)", re.M)),
    ("build.gradle.kts", re.compile(r'^\s*version\s*=\s*"([^"]+)"', re.M)),
    ("build.gradle", re.compile(r"^\s*version\s*=?\s*['\"]([^'\"]+)['\"]", re.M)),
]
found = []


def read(name):
    p = os.path.join(root, name)
    return open(p, encoding="utf-8").read() if os.path.isfile(p) else None


for name, rx in PATTERNS:
    text = read(name)
    if text is None:
        continue
    for m in rx.finditer(text):
        line = text[:m.start()].count("\n") + 1
        note = "indented (inside a block, e.g. subprojects)" if m.group(0)[0] in " \t" else ""
        found.append((name, line, m.group(m.lastindex), note))

pkg = read("package.json")
if pkg:
    try:
        v = json.loads(pkg).get("version")
        if v:
            found.append(("package.json", 0, v, "npm version <bump> --no-git-tag-version also updates package-lock.json"))
    except ValueError:
        pass

for name in ("version.properties", "src/main/resources/version.properties"):
    t = read(name)
    m = t and re.search(r"version\s*=\s*(\S+)", t)
    if m:
        found.append((name, 0, m.group(1), "usually generated by the build; do not edit"))

for name, line, v, note in found:
    print(f"{name}{':' + str(line) if line else ''}\t{v}\t{note}")
if not found:
    print("No version found in gradle.properties, build.gradle(.kts) or package.json. Check the README, manifests, workflows.")

tags = subprocess.run(["git", "tag", "--sort=-v:refname"], cwd=root, capture_output=True, text=True).stdout.split()
print("last tag\t" + (tags[0] if tags else "(none)"))
